const TABLES: Record<string, Record<string, QuickGloss>> = { es: ES, en: EN };

/**
 * An instant answer for a function word, or null when the word needs the
 * model's judgement. `textLang` is the language of the word being clicked.
 */
export function quickGloss(textLang: string, term: string): QuickGloss | null {
  const table = TABLES[textLang];
  if (!table) return null;
  return table[term.toLocaleLowerCase(textLang)] ?? null;
}

/** The words the background sweep can skip, because this file answers them. */
export function knownWords(textLang: string): string[] {
  return Object.keys(TABLES[textLang] ?? {});
}
